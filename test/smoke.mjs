#!/usr/bin/env node
/**
 * End-to-end MCP smoke test in fixture mode (YT_FIXTURES=test/fixtures, no network).
 *  - Spawns the built server (dist/index.js) over stdio with the MCP SDK Client
 *  - Lists tools and calls every tool, including error paths (typed error codes)
 *  - Verifies billing: BILLING=log prints one charge per *successful* call only
 *  - Briefly checks Streamable HTTP mode (--http): readiness probe GET / + a tool call
 *  - Writes demo/transcript.json and demo/transcript.md
 * Exits non-zero on any failed assertion.
 */
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import { StreamableHTTPClientTransport } from "@modelcontextprotocol/sdk/client/streamableHttp.js";
import { spawn } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SERVER = join(ROOT, "dist", "index.js");
const DEMO = join(ROOT, "demo");
const FIXTURES = process.env.YT_FIXTURES || join(ROOT, "test", "fixtures");
const SOLAR = "kM3pLz8QwT0"; // manual captions + description chapters
const BREAD = "Vb7nQe2RtY4"; // auto-generated captions only, no chapters
const LOFI = "NoCapt10n00"; // captions disabled, tracklist chapters in description

const ENV = { ...process.env, YT_FIXTURES: FIXTURES, BILLING: "log", APIFY_IS_AT_HOME: "" };

const transcript = {
  generatedAt: new Date().toISOString(),
  mode: `fixtures (${FIXTURES.replace(ROOT + "/", "")})`,
  server: null,
  tools: [],
  calls: [],
  billing: null,
  http: null,
  assertions: [],
};
let failures = 0;
const successes = {};

function check(name, cond, detail = "") {
  transcript.assertions.push({ name, passed: !!cond, ...(detail ? { detail } : {}) });
  console.log(`${cond ? "  ✔" : "  ✘"} ${name}${detail && !cond ? ` — ${detail}` : ""}`);
  if (!cond) failures++;
}

async function call(client, name, args, { expectError = false } = {}) {
  const started = Date.now();
  let result;
  try {
    result = await client.callTool({ name, arguments: args }, undefined, { timeout: 60_000 });
  } catch (err) {
    result = { isError: true, content: [{ type: "text", text: String(err?.message ?? err) }], protocolError: true };
  }
  const ms = Date.now() - started;
  const data = result.structuredContent ?? null;
  if (!result.isError) successes[name] = (successes[name] ?? 0) + 1;
  transcript.calls.push({ tool: name, arguments: args, durationMs: ms, isError: !!result.isError, result });
  console.log(`→ ${name} ${JSON.stringify(args)} (${ms} ms)${result.isError ? ` [error ${data?.error?.code ?? ""}]` : ""}`);
  if (!expectError && result.isError) console.log("    ", result.content?.[0]?.text);
  return { result, data };
}

async function runStdio() {
  const transport = new StdioClientTransport({ command: process.execPath, args: [SERVER], env: ENV, stderr: "pipe" });
  const stderr = [];
  transport.stderr?.on("data", (d) => stderr.push(String(d)));
  const client = new Client({ name: "smoke-test", version: "1.0.0" });
  await client.connect(transport);

  transcript.server = { ...client.getServerVersion(), instructions: client.getInstructions() };
  console.log(`Connected to ${transcript.server.name} ${transcript.server.version}`);

  // --- tools/list -------------------------------------------------------------
  const { tools } = await client.listTools();
  transcript.tools = tools;
  const names = tools.map((t) => t.name).sort();
  check("lists 4 tools", JSON.stringify(names) === JSON.stringify(["get_transcript", "get_video_chapters", "search_videos", "summarize_transcript"]), names.join(","));
  check("every tool has an input schema, description and read-only annotation", tools.every((t) => t.inputSchema?.type === "object" && t.description && t.annotations?.readOnlyHint));

  // --- get_transcript -----------------------------------------------------------
  {
    const { result, data } = await call(client, "get_transcript", { video: SOLAR });
    check("get_transcript ok", !result.isError);
    check("get_transcript metadata (title, channel, duration)", data?.video?.title?.startsWith("How Solar Panels") && data.video.channel === "Bright Circuits" && data.video.durationSeconds === 552 && data.video.duration === "9:12");
    check("get_transcript lists available languages with auto flag", data?.availableLanguages?.length === 3 && data.availableLanguages.some((l) => l.autoGenerated) && data.availableLanguages.some((l) => l.languageCode === "es"));
    check("get_transcript prefers manual English", data?.transcript?.language === "en" && data.transcript.autoGenerated === false);
    check("get_transcript text content", typeof data?.transcript?.content === "string" && data.transcript.content.includes("p-n junction") && data.transcript.wordCount > 800);
  }
  {
    const { result, data } = await call(client, "get_transcript", { video: `https://youtu.be/${SOLAR}?si=share`, format: "segments", include_timestamps: true });
    const seg = data?.transcript?.segments?.[1];
    check("get_transcript segments via youtu.be URL", !result.isError && data.transcript.segments.length === data.transcript.segmentCount);
    check("segments carry start/duration/time", seg && typeof seg.start === "number" && typeof seg.duration === "number" && /^\d+:\d\d$/.test(seg.time));
  }
  {
    const { data } = await call(client, "get_transcript", { video: SOLAR, format: "text", include_timestamps: true, max_chars: 1200 });
    check("text with timestamps + max_chars truncation", /^\[0:00\] /.test(data?.transcript?.content ?? "") && data.transcript.truncated === true && data.transcript.content.length <= 1200);
  }
  {
    const { data } = await call(client, "get_transcript", { video: SOLAR, format: "srt" });
    check("SRT format", /^1\n00:00:00,000 --> 00:00:0\d,\d{3}\nHey everyone/.test(data?.transcript?.content ?? ""));
  }
  {
    const { result, data } = await call(client, "get_transcript", { video: BREAD, languages: ["en"] });
    check("auto-generated transcript flagged", !result.isError && data.transcript.autoGenerated === true);
  }
  {
    const { result, data } = await call(client, "get_transcript", { video: SOLAR, translate_to: "de", format: "segments" });
    check("translate_to=de returns translated transcript", !result.isError && data.transcript.language === "de" && data.transcript.translatedFrom === "en" && /Hallo/.test(data.transcript.segments[0].text));
  }
  {
    const { result, data } = await call(client, "get_transcript", { video: "FrenchOnly0", languages: ["en", "de"] });
    check("falls back to available language with a note", !result.isError && data.transcript.language === "fr" && data.transcript.matchedPreference === false && data.notes?.length === 1);
  }

  // --- search_videos ----------------------------------------------------------
  {
    const { result, data } = await call(client, "search_videos", { query: "solar panels", limit: 8, duration: "medium", features: ["subtitles"] });
    check("search_videos ok", !result.isError);
    check("search_videos paginates to 8 results", data?.count === 8 && data.videos.length === 8);
    check("search_videos result shape", data?.videos?.every((v) => v.videoId && v.title && v.url.includes(v.videoId) && "channel" in v && "durationSeconds" in v));
    check("search_videos echoes filters", data?.filters?.duration === "medium" && data.filters.features?.[0] === "subtitles");
  }
  {
    const { result, data } = await call(client, "search_videos", { query: "zxqv no such video", limit: 5 });
    check("search_videos empty result is not an error", !result.isError && data.count === 0 && !!data.note);
  }

  // --- get_video_chapters ---------------------------------------------------------
  {
    const { result, data } = await call(client, "get_video_chapters", { video: SOLAR });
    check("chapters from description", !result.isError && data.source === "description" && data.chapterCount === 7);
    check("chapter shape (start/end/url)", data?.chapters?.[1]?.start === 42 && data.chapters[1].url.endsWith("&t=42s") && data.chapters[6].end === 552);
  }
  {
    const { result, data } = await call(client, "get_video_chapters", { video: BREAD });
    check("chapters derived from transcript", !result.isError && data.source === "transcript" && data.chapterCount >= 3);
    check("derived chapters have keywords + summary", data?.chapters?.every((c) => c.keywords?.length && c.summary));
  }
  {
    const { result, data } = await call(client, "get_video_chapters", { video: LOFI });
    check("description chapters work even when captions are disabled", !result.isError && data.source === "description" && data.chapterCount === 8);
  }
  {
    const { result, data } = await call(client, "get_video_chapters", { video: SOLAR, source: "transcript", target_chapters: 4 });
    check("source=transcript forces derivation", !result.isError && data.source === "transcript" && data.chapterCount >= 3 && data.chapterCount <= 5);
  }

  // --- summarize_transcript -----------------------------------------------------------
  {
    const { result, data } = await call(client, "summarize_transcript", { video: SOLAR, max_points: 6 });
    check("summarize_transcript ok", !result.isError);
    check("summary has 6 timestamped key points", data?.keyPoints?.length === 6 && data.keyPoints.every((p) => p.timestamp && p.url.includes("&t=") || p.start < 1));
    check("summary uses creator chapters with bullets", data?.chapterSource === "description" && data.chapters.length === 7 && data.chapters.every((c) => c.bullets.length >= 1));
    check("summary keywords + quotes", data?.keywords?.some((k) => k.term === "inverter") && data.quotes.length === 3);
  }
  {
    const { result, data } = await call(client, "summarize_transcript", { video: BREAD, max_points: 5, bullets_per_chapter: 1 });
    check("summary of ASR transcript with derived chapters", !result.isError && data.chapterSource === "transcript" && data.keyPoints.length === 5);
  }

  // --- error handling ------------------------------------------------------------------
  const errorCases = [
    ["get_transcript", { video: LOFI }, "TRANSCRIPTS_DISABLED"],
    ["get_transcript", { video: "Pr1vAtEvid0" }, "VIDEO_PRIVATE"],
    ["get_transcript", { video: "AgeRstrct01" }, "AGE_RESTRICTED"],
    ["get_transcript", { video: "Unavail0000" }, "VIDEO_UNAVAILABLE"],
    ["get_transcript", { video: "RateLimit00" }, "REQUEST_BLOCKED"],
    ["get_video_chapters", { video: "CaptchaVid0" }, "REQUEST_BLOCKED"],
    ["get_transcript", { video: "B0tCheck000" }, "REQUEST_BLOCKED"],
    ["get_transcript", { video: "not a video" }, "INVALID_VIDEO_ID"],
    ["get_transcript", { video: SOLAR, languages: ["ja"], fallback_to_any_language: false }, "NO_TRANSCRIPT_FOUND"],
    ["get_video_chapters", { video: BREAD, source: "description" }, "NO_CHAPTERS"],
    ["summarize_transcript", { video: LOFI }, "TRANSCRIPTS_DISABLED"],
  ];
  for (const [tool, args, code] of errorCases) {
    const { result, data } = await call(client, tool, args, { expectError: true });
    check(`${tool} ${JSON.stringify(args)} → ${code}`, result.isError && data?.error?.code === code && result.content[0].text.startsWith(`Error (${code})`), result.content?.[0]?.text);
  }
  {
    const { result } = await call(client, "search_videos", { query: "x", limit: 51 }, { expectError: true });
    check("limit > 50 rejected by schema", result.isError);
  }
  {
    const { result, data } = await call(client, "get_transcript", { video: "RateLimit00" }, { expectError: true });
    check("blocked error is marked retryable", result.isError && data?.error?.retryable === true);
  }

  await client.close();
  return stderr.join("");
}

function checkBilling(stderr) {
  const charged = {};
  for (const m of stderr.matchAll(/\[billing\] charge (\S+) x(\d+)/g)) charged[m[1]] = (charged[m[1]] ?? 0) + Number(m[2]);
  const expected = {
    transcript: successes.get_transcript ?? 0,
    search: successes.search_videos ?? 0,
    chapters: successes.get_video_chapters ?? 0,
    summary: successes.summarize_transcript ?? 0,
  };
  transcript.billing = { expected, charged };
  console.log(`billing: expected ${JSON.stringify(expected)} charged ${JSON.stringify(charged)}`);
  check("billing: one event per successful call, none for failures", JSON.stringify(expected) === JSON.stringify({ transcript: charged.transcript ?? 0, search: charged.search ?? 0, chapters: charged.chapters ?? 0, summary: charged.summary ?? 0 }) && Object.keys(charged).length === 4);
}

async function runHttp() {
  const child = spawn(process.execPath, [SERVER, "--http", "--port", "0"], { stdio: ["ignore", "ignore", "pipe"], env: { ...ENV, BILLING: "" } });
  try {
    const url = await new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error("HTTP server did not start")), 10_000);
      let buf = "";
      child.stderr.on("data", (d) => {
        buf += d;
        const m = buf.match(/(http:\/\/\S+\/mcp)/);
        if (m) {
          clearTimeout(timer);
          resolve(m[1]);
        }
      });
      child.on("exit", (code) => reject(new Error(`HTTP server exited with ${code}: ${buf}`)));
    });
    const probe = await fetch(url.replace(/\/mcp$/, "/"), { headers: { "x-apify-container-server-readiness-probe": "1" } });
    const health = await probe.json();
    const client = new Client({ name: "smoke-test-http", version: "1.0.0" });
    await client.connect(new StreamableHTTPClientTransport(new URL(url)));
    const { tools } = await client.listTools();
    const res = await client.callTool({ name: "get_transcript", arguments: { video: SOLAR, format: "segments" } });
    await client.close();
    transcript.http = {
      url,
      readinessProbe: { status: probe.status, body: health },
      tools: tools.map((t) => t.name),
      sampleCall: { tool: "get_transcript", isError: !!res.isError, title: res.structuredContent?.video?.title, segments: res.structuredContent?.transcript?.segmentCount },
    };
    console.log(`→ HTTP ${url}: ${tools.length} tools`);
    check("HTTP mode: readiness probe GET / → 200", probe.status === 200 && health?.status === "ok");
    check("HTTP mode: lists 4 tools", tools.length === 4);
    check("HTTP mode: tool call works", !res.isError && res.structuredContent?.transcript?.segmentCount > 100);
  } finally {
    child.kill("SIGTERM");
  }
}

// --- Markdown rendering ----------------------------------------------------------------
const fence = (obj, max = 3500) => {
  let s = typeof obj === "string" ? obj : JSON.stringify(obj, null, 2);
  if (s.length > max) s = s.slice(0, max) + `\n… (truncated, ${s.length - max} more chars — see transcript.json)`;
  return "```json\n" + s + "\n```";
};
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

function renderCall(c) {
  const out = [`### \`${c.tool}\` ${c.isError ? "⚠️ (error)" : ""}`, "", `Arguments: \`${JSON.stringify(c.arguments)}\` · ${c.durationMs} ms`, ""];
  const d = c.result.structuredContent;
  if (c.isError || !d) {
    out.push("> " + esc(c.result.content?.[0]?.text), "");
    return out.join("\n");
  }
  if (c.tool === "get_transcript") {
    const v = d.video;
    const t = d.transcript;
    out.push(`**${esc(v.title)}** · ${esc(v.channel)} · ${v.duration} · ${v.viewCount?.toLocaleString("en-US") ?? "–"} views`, "");
    out.push(`Transcript: \`${t.language}\` (${t.languageName})${t.autoGenerated ? " · auto-generated" : " · manual"}${t.translatedFrom ? ` · translated from ${t.translatedFrom}` : ""} · ${t.segmentCount} segments · ${t.wordCount} words · format \`${t.format}\`${t.truncated ? " · truncated" : ""}`, "");
    out.push(`Available: ${d.availableLanguages.map((l) => `\`${l.languageCode}\`${l.autoGenerated ? " (auto)" : ""}`).join(", ")}`, "");
    if (d.notes) out.push(`_${d.notes.join(" ")}_`, "");
    const sample = t.content ?? t.segments.slice(0, 4).map((s) => `${s.time ?? s.start} ${s.text}`).join("\n");
    out.push("```", String(sample).slice(0, 600) + (String(sample).length > 600 ? " …" : ""), "```");
  } else if (c.tool === "search_videos") {
    out.push(`${d.count} results${d.estimatedResults ? ` (≈${d.estimatedResults.toLocaleString("en-US")} total)` : ""}`, "");
    if (d.count) {
      out.push("| id | title | channel | duration | views | published |", "|---|---|---|---|---|---|");
      for (const v of d.videos) out.push(`| ${v.videoId} | ${esc(v.title)} | ${esc(v.channel)} | ${v.duration ?? (v.isLive ? "LIVE" : "–")} | ${v.viewCount?.toLocaleString("en-US") ?? "–"} | ${v.published ?? "–"} |`);
    } else out.push(`_${d.note}_`);
  } else if (c.tool === "get_video_chapters") {
    out.push(`**${esc(d.video.title)}** — source: **${d.source}** · ${d.chapterCount} chapters`, "");
    out.push("| # | start | title | keywords |", "|---|---|---|---|");
    for (const ch of d.chapters) out.push(`| ${ch.index} | [${ch.startTime}](${ch.url}) | ${esc(ch.title)} | ${esc(ch.keywords?.join(", ") ?? "")} |`);
  } else if (c.tool === "summarize_transcript") {
    out.push(`**${esc(d.video.title)}** — ${d.method}`, "", `**TL;DR:** ${esc(d.tldr)}`, "", "**Key points**", "");
    for (const p of d.keyPoints) out.push(`- [${p.timestamp}](${p.url}) ${esc(p.text)}`);
    out.push("", `**Keywords:** ${d.keywords.map((k) => `${k.term} (${k.count})`).join(", ")}`, "", `**Chapters** (${d.chapterSource})`, "");
    for (const ch of d.chapters) {
      out.push(`- **${esc(ch.title)}** [${ch.startTime}](${ch.url})`);
      for (const b of ch.bullets) out.push(`  - [${b.timestamp}](${b.url}) ${esc(b.text)}`);
    }
    if (d.quotes.length) {
      out.push("", "**Quotes**", "");
      for (const q of d.quotes) out.push(`> “${esc(q.text)}” — [${q.timestamp}](${q.url})`, ">");
    }
  }
  out.push("", "<details><summary>Raw response</summary>", "", fence(d), "", "</details>", "");
  return out.join("\n");
}

function renderMarkdown() {
  const passed = transcript.assertions.filter((a) => a.passed).length;
  return [
    `# youtube-transcripts-mcp — smoke test transcript`,
    "",
    `Generated ${transcript.generatedAt} by \`test/smoke.mjs\` in **${transcript.mode}** mode (recorded, hand-made YouTube responses; no network). Server: **${transcript.server?.name} ${transcript.server?.version}** over stdio.`,
    "",
    `**Assertions: ${passed}/${transcript.assertions.length} passed.**`,
    "",
    "## Tools",
    "",
    ...transcript.tools.map(
      (t) =>
        `- **\`${t.name}\`** — ${t.description}\n  - params: ${Object.entries(t.inputSchema.properties ?? {})
          .map(([k, v]) => `\`${k}\`${(t.inputSchema.required ?? []).includes(k) ? "*" : ""} (${v.type ?? (v.anyOf ? v.anyOf.map((x) => x.type).join("|") : "?")})`)
          .join(", ")}`,
    ),
    "",
    "## Calls",
    "",
    ...transcript.calls.map(renderCall),
    "## Billing (BILLING=log)",
    "",
    transcript.billing ? fence(transcript.billing) : "_not run_",
    "",
    "## Streamable HTTP mode",
    "",
    transcript.http ? fence(transcript.http) : "_not run_",
    "",
    "## Assertions",
    "",
    ...transcript.assertions.map((a) => `- ${a.passed ? "✅" : "❌"} ${a.name}${a.detail && !a.passed ? ` — ${a.detail}` : ""}`),
    "",
  ].join("\n");
}

async function main() {
  try {
    const stderr = await runStdio();
    checkBilling(stderr);
    await runHttp();
  } catch (err) {
    check("smoke test ran to completion", false, String(err?.stack ?? err));
  }
  await mkdir(DEMO, { recursive: true });
  await writeFile(join(DEMO, "transcript.json"), JSON.stringify(transcript, null, 2));
  await writeFile(join(DEMO, "transcript.md"), renderMarkdown());
  const passed = transcript.assertions.filter((a) => a.passed).length;
  console.log(`\n${passed}/${transcript.assertions.length} assertions passed. Transcript → demo/transcript.{json,md}`);
  process.exit(failures ? 1 : 0);
}

main();
