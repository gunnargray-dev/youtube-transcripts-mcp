/** Player parsing, track selection and error mapping against recorded fixtures (YT_FIXTURES mode). */
import assert from "node:assert/strict";
import { test } from "node:test";
import { FIXTURES, dist, fixtureJson, rejection } from "./helpers.mjs";

process.env.YT_FIXTURES = FIXTURES;
const yt = await dist("youtube.js");
const { toErrorPayload } = await dist("server.js");

const SOLAR = "kM3pLz8QwT0";
const BREAD = "Vb7nQe2RtY4";
const opts = (o = {}) => ({ languages: ["en"], allowAutoGenerated: true, fallbackToAny: true, ...o });

test("buildVideoInfo + parseCaptionTracks read ANDROID player responses", () => {
  const info = yt.buildVideoInfo(SOLAR, fixtureJson(`player/${SOLAR}.json`), null);
  assert.equal(info.title, "How Solar Panels Actually Work (Explained Simply)");
  assert.equal(info.channel, "Bright Circuits");
  assert.equal(info.durationSeconds, 552);
  assert.equal(info.viewCount, 1843291);
  assert.deepEqual(
    info.tracks.map((t) => [t.languageCode, t.languageName, t.autoGenerated]),
    [["en", "English", false], ["es", "Spanish", false], ["en", "English", true]],
  );
  assert.ok(info.translationLanguages.some((l) => l.languageCode === "de" && l.languageName === "German"));
  assert.ok(info.tracks[0].baseUrl.startsWith("https://www.youtube.com/api/timedtext?v=kM3pLz8QwT0"));
});

test("assertPlayable maps playability statuses to error codes", () => {
  const cases = {
    Pr1vAtEvid0: "VIDEO_PRIVATE",
    AgeRstrct01: "AGE_RESTRICTED",
    B0tCheck000: "REQUEST_BLOCKED",
    Unavail0000: "VIDEO_UNAVAILABLE",
    MembersOnly: "VIDEO_UNPLAYABLE",
  };
  for (const [id, code] of Object.entries(cases)) {
    assert.throws(() => yt.assertPlayable(fixtureJson(`player/${id}.json`), id), (e) => e.code === code, id);
  }
  assert.doesNotThrow(() => yt.assertPlayable(fixtureJson(`player/${SOLAR}.json`), SOLAR));
});

test("selectTrack: manual beats auto, base-language match, fallback, translation", () => {
  const info = yt.buildVideoInfo(SOLAR, fixtureJson(`player/${SOLAR}.json`), null);
  let c = yt.selectTrack(info, opts());
  assert.equal(c.track.autoGenerated, false);
  assert.equal(c.matchedPreference, true);

  c = yt.selectTrack(info, opts({ languages: ["en-GB"] }));
  assert.equal(c.track.languageCode, "en", "en-GB falls back to en");

  c = yt.selectTrack(info, opts({ languages: ["fr", "es"] }));
  assert.equal(c.track.languageCode, "es", "priority order respected");

  c = yt.selectTrack(info, opts({ languages: ["ja"] }));
  assert.equal(c.matchedPreference, false, "fallback to best available");
  assert.equal(c.track.languageCode, "en");

  assert.throws(
    () => yt.selectTrack(info, opts({ languages: ["ja"], fallbackToAny: false })),
    (e) => e.code === "NO_TRANSCRIPT_FOUND" && e.details.available.length === 3,
  );

  c = yt.selectTrack(info, opts({ translateTo: "de" }));
  assert.equal(c.translatedTo, "de");
  c = yt.selectTrack(info, opts({ languages: ["en"], translateTo: "es" }));
  assert.equal(c.translatedTo, null, "uses the existing es track rather than translating");
  assert.equal(c.track.languageCode, "es");

  const bread = yt.buildVideoInfo(BREAD, fixtureJson(`player/${BREAD}.json`), null);
  assert.throws(
    () => yt.selectTrack(bread, opts({ allowAutoGenerated: false, fallbackToAny: false })),
    (e) => e.code === "NO_TRANSCRIPT_FOUND",
  );
  const noCaps = yt.buildVideoInfo("NoCapt10n00", fixtureJson("player/NoCapt10n00.json"), null);
  assert.throws(() => yt.selectTrack(noCaps, opts()), (e) => e.code === "TRANSCRIPTS_DISABLED");
  const fr = yt.buildVideoInfo("FrenchOnly0", fixtureJson("player/FrenchOnly0.json"), null);
  assert.throws(() => yt.selectTrack(fr, opts({ translateTo: "en" })), (e) => e.code === "TRANSLATION_UNAVAILABLE");
});

test("getTranscript fetches player → timedtext, no watch page (fixtures)", async () => {
  const r = await yt.getTranscript(SOLAR, opts());
  assert.equal(r.info.publishDate, "2025-03-14T07:00:12-07:00");
  assert.equal(r.info.category, "Education");
  assert.ok(r.segments.length > 100);
  assert.equal(r.fetch.cached, false);
  assert.equal(r.fetch.timings.watchPageMs, 0, "watch page is skipped when the player response has the metadata");
  for (const k of ["proxySetupMs", "playerMs", "watchPageMs", "timedtextMs", "totalMs"]) assert.equal(typeof r.fetch.timings[k], "number", k);
  assert.ok(r.fetch.timings.totalMs >= r.fetch.timings.playerMs + r.fetch.timings.timedtextMs);
  const again = await yt.getTranscript(SOLAR, opts());
  assert.equal(again.fetch.cached, true, "second call served from cache");

  const de = await yt.getTranscript(SOLAR, opts({ translateTo: "de" }));
  assert.match(de.segments[0].text, /Hallo zusammen/);

  const asr = await yt.getTranscript(BREAD, opts());
  assert.equal(asr.choice.track.autoGenerated, true);
  assert.ok(asr.segments.length > 80);
});

test("getTranscript error mapping", async () => {
  const cases = {
    NoCapt10n00: "TRANSCRIPTS_DISABLED",
    Pr1vAtEvid0: "VIDEO_PRIVATE",
    AgeRstrct01: "AGE_RESTRICTED",
    B0tCheck000: "REQUEST_BLOCKED",
    RateLimit00: "REQUEST_BLOCKED",
    Unavail0000: "VIDEO_UNAVAILABLE",
    ZZZnotThere: "VIDEO_UNAVAILABLE",
    MembersOnly: "VIDEO_UNPLAYABLE",
    PoTokenVid0: "PO_TOKEN_REQUIRED",
    EmptyCapt00: "EMPTY_TRANSCRIPT",
  };
  for (const [id, code] of Object.entries(cases)) {
    const err = await rejection(yt.getTranscript(id, opts()));
    assert.equal(err.code, code, `${id}: ${err.message}`);
    const payload = toErrorPayload(err);
    assert.equal(payload.code, code);
    assert.equal(payload.retryable, ["REQUEST_BLOCKED", "EMPTY_TRANSCRIPT"].includes(code), `${id} retryable flag`);
  }
  // reCAPTCHA is only detectable on the watch page, which getVideoInfo (chapters) still fetches.
  const captcha = await rejection(yt.getVideoInfo("CaptchaVid0"));
  assert.equal(captcha.code, "REQUEST_BLOCKED");
  assert.equal(captcha.details.captcha, true);
  const rate = await rejection(yt.getTranscript("RateLimit00", opts()));
  assert.equal(rate.details.httpStatus, 429);
  assert.equal(toErrorPayload(new Error("boom")).code, "INTERNAL_ERROR");
});

test("extractJsonAfter + parseMarkerChapters read watch-page chapter markers", () => {
  const data = {
    playerOverlays: {
      playerOverlayRenderer: {
        decoratedPlayerBarRenderer: {
          decoratedPlayerBarRenderer: {
            playerBar: {
              multiMarkersPlayerBarRenderer: {
                markersMap: [
                  {
                    key: "AUTO_CHAPTERS",
                    value: {
                      chapters: [
                        { chapterRenderer: { title: { simpleText: "Intro" }, timeRangeStartMillis: 0 } },
                        { chapterRenderer: { title: { simpleText: "Setup {braces} \"quoted\"" }, timeRangeStartMillis: 61000 } },
                      ],
                    },
                  },
                ],
              },
            },
          },
        },
      },
    },
  };
  const html = `<script>var ytInitialData = ${JSON.stringify(data)};</script><script>var other = {"a":1};</script>`;
  const parsed = yt.extractJsonAfter(html, "ytInitialData");
  assert.deepEqual(parsed, data);
  assert.deepEqual(yt.parseMarkerChapters(parsed), {
    kind: "auto",
    chapters: [
      { title: "Intro", start: 0 },
      { title: 'Setup {braces} "quoted"', start: 61 },
    ],
  });
  assert.equal(yt.extractJsonAfter("<html></html>", "ytInitialData"), null);
});
