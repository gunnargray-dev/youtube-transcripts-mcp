#!/usr/bin/env node
/**
 * Live test against a DEPLOYED Standby endpoint (not run by `npm test`).
 *
 *   MCP_URL=https://<user>--youtube-transcripts-mcp.apify.actor/mcp \
 *   APIFY_TOKEN=apify_api_xxx node test/live-remote.mjs
 *
 * Uses the same 5 videos as FEASIBILITY_probe.json, so results are comparable
 * (expected with datacenter proxy: 4/5 OK, 9bZkp7q19f0 → NO_TRANSCRIPT_FOUND or
 * TRANSCRIPTS_DISABLED). Every successful call is a billable event on your account.
 * Writes demo/live_remote.json.
 */
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StreamableHTTPClientTransport } from "@modelcontextprotocol/sdk/client/streamableHttp.js";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const MCP_URL = process.env.MCP_URL;
const TOKEN = process.env.APIFY_TOKEN;
if (!MCP_URL || !TOKEN) {
  console.error("Set MCP_URL (…/mcp of the Actor's Standby URL) and APIFY_TOKEN.");
  process.exit(2);
}
const VIDEOS = ["dQw4w9WgXcQ", "jNQXAC9IVRw", "aircAruvnKk", "kJQP7kiw5Fk", "9bZkp7q19f0"];
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "demo", "live_remote.json");

const transport = new StreamableHTTPClientTransport(new URL(MCP_URL), {
  requestInit: { headers: { Authorization: `Bearer ${TOKEN}` } },
});
const client = new Client({ name: "live-remote-test", version: "1.0.0" });
await client.connect(transport);

const report = { url: MCP_URL, startedAt: new Date().toISOString(), tools: [], transcripts: [], calls: {} };
report.tools = (await client.listTools()).tools.map((t) => t.name);
console.log("tools:", report.tools.join(", "));

async function call(name, args) {
  const t0 = Date.now();
  const r = await client.callTool({ name, arguments: args }, undefined, { timeout: 180_000 });
  const ms = Date.now() - t0;
  const d = r.structuredContent ?? {};
  return { ok: !r.isError, ms, data: d, error: r.isError ? (d.error ?? { message: r.content?.[0]?.text }) : null };
}

for (const id of VIDEOS) {
  const r = await call("get_transcript", { video: id, format: "segments" });
  const row = r.ok
    ? {
        id,
        ok: true,
        segments: r.data.transcript.segmentCount,
        language: r.data.transcript.language,
        autoGenerated: r.data.transcript.autoGenerated,
        title: r.data.video.title,
        attempts: r.data.fetch?.attempts,
        ms: r.ms,
      }
    : { id, ok: false, code: r.error?.code, message: r.error?.message, ms: r.ms };
  report.transcripts.push(row);
  console.log(row.ok ? `OK   ${id} ${row.segments} segs ${row.language}${row.autoGenerated ? " (auto)" : ""} ${row.ms} ms, attempts=${row.attempts}` : `FAIL ${id} ${row.code} ${row.ms} ms`);
}

const s = await call("search_videos", { query: "how solar panels work", limit: 5, features: ["subtitles"] });
report.calls.search_videos = { ok: s.ok, ms: s.ms, count: s.data.count, first: s.data.videos?.[0]?.title, error: s.error };
const c = await call("get_video_chapters", { video: "aircAruvnKk" });
report.calls.get_video_chapters = { ok: c.ok, ms: c.ms, source: c.data.source, chapters: c.data.chapters?.map((x) => `${x.startTime} ${x.title}`), error: c.error };
const m = await call("summarize_transcript", { video: "aircAruvnKk", max_points: 5 });
report.calls.summarize_transcript = { ok: m.ok, ms: m.ms, tldr: m.data.tldr, keywords: m.data.keywords?.map((k) => k.term), error: m.error };
console.log(JSON.stringify(report.calls, null, 1));

report.summary = `${report.transcripts.filter((t) => t.ok).length}/${VIDEOS.length} transcripts OK`;
console.log(report.summary);
await client.close();
await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, JSON.stringify(report, null, 2));
console.log(`→ ${OUT}`);
