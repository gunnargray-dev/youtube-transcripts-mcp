/**
 * YouTube video metadata + transcript retrieval, modelled on the Python
 * `youtube-transcript-api`:
 *
 *  1. POST https://www.youtube.com/youtubei/v1/player with the ANDROID client
 *     context → videoDetails + captionTracks + microformat (no API key needed)
 *  2. GET  <captionTrack.baseUrl> (srv1 XML; json3 / srv3 also parsed)
 *
 * The (~1 MB) watch page is only fetched when it is really needed: chapter
 * markers for get_chapters, or as a fallback to obtain the InnerTube API key
 * when the keyless player call is rejected.
 *
 * All requests for one video run in the same proxy session because the
 * caption URLs are signed for the requesting IP.
 */
import { type HttpClient, withYouTube } from "./http.js";
import { type Segment, parseTimedText } from "./transcript.js";
import { ErrorCodes, TtlCache, YouTubeError, decodeEntities, normalizeLang, videoUrl } from "./util.js";

const WATCH_URL = "https://www.youtube.com/watch?v=";
const PLAYER_URL = "https://www.youtube.com/youtubei/v1/player";
export const INNERTUBE_ANDROID_CONTEXT = {
  client: { clientName: "ANDROID", clientVersion: "20.10.38", hl: "en", gl: "US" },
} as const;

const CACHE_TTL_MS = Number(process.env.CACHE_TTL_MS ?? 10 * 60_000);
const infoCache = new TtlCache<VideoInfo>(CACHE_TTL_MS, 300);
const transcriptCache = new TtlCache<Segment[]>(CACHE_TTL_MS, 200);

export interface CaptionTrack {
  languageCode: string;
  languageName: string;
  autoGenerated: boolean;
  translatable: boolean;
  baseUrl: string;
}

export interface MarkerChapter {
  title: string;
  start: number;
}

export interface VideoInfo {
  id: string;
  url: string;
  title: string;
  channel: string | null;
  channelId: string | null;
  durationSeconds: number | null;
  viewCount: number | null;
  publishDate: string | null;
  category: string | null;
  isLive: boolean;
  keywords: string[];
  description: string;
  tracks: CaptionTrack[];
  translationLanguages: { languageCode: string; languageName: string }[];
  /** Chapters from the watch page player bar (creator chapters or YouTube's auto chapters). */
  markerChapters: { kind: "description" | "auto"; chapters: MarkerChapter[] } | null;
  /** True once the watch page was parsed (markerChapters is authoritative; publishDate/category filled from it). */
  watchLoaded?: boolean;
}

export interface FetchTimings {
  proxySetupMs: number;
  playerMs: number;
  watchPageMs: number;
  timedtextMs: number;
  totalMs: number;
}

const newTimings = (): FetchTimings => ({ proxySetupMs: 0, playerMs: 0, watchPageMs: 0, timedtextMs: 0, totalMs: 0 });

async function timed<T>(t: FetchTimings, key: "playerMs" | "watchPageMs" | "timedtextMs", fn: () => Promise<T>): Promise<T> {
  const t0 = Date.now();
  try {
    return await fn();
  } finally {
    t[key] += Date.now() - t0;
  }
}

