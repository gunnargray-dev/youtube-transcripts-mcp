export interface FetchMeta {
  attempts: number;
  proxy: string | null;
  cached: boolean;
  timings: FetchTimings;
}

/** One stderr line per network operation so slow phases are visible in the Actor log. */
function logTimings(op: string, id: string, f: FetchMeta): void {
  const t = f.timings;
  console.error(
    `[fetch] ${op} ${id} attempts=${f.attempts} cached=${f.cached} proxySetupMs=${t.proxySetupMs} playerMs=${t.playerMs} ` +
      `watchPageMs=${t.watchPageMs} timedtextMs=${t.timedtextMs} totalMs=${t.totalMs}`,
  );
}

/** Session that produced each cached VideoInfo: signed caption URLs are only valid from that exit IP. */
const infoSession = new Map<string, string | null>();

/** Video metadata + caption track list (no caption download). Includes watch-page data (chapter markers). */
export async function getVideoInfo(id: string): Promise<{ info: VideoInfo; fetch: FetchMeta }> {
  const start = Date.now();
  const hit = infoCache.get(id);
  if (hit?.watchLoaded) {
    return { info: hit, fetch: { attempts: 0, proxy: null, cached: true, timings: { ...newTimings(), totalMs: Date.now() - start } } };
  }
  const result = await withYouTube(async (http, ctx) => {
    const t = newTimings();
    t.proxySetupMs = ctx.proxySetupMs;
    let info: VideoInfo;
    if (hit) {
      // Player data is cached (from a transcript call); only the watch page is missing.
      const page = await timed(t, "watchPageMs", () => fetchWatchPage(http, id));
      info = { ...hit, publishDate: page.publishDate ?? hit.publishDate, category: page.category ?? hit.category, markerChapters: page.markerChapters, watchLoaded: true };
      infoCache.set(id, info);
    } else {
      info = await loadInfo(http, id, t, true);
      infoSession.set(id, ctx.sessionId);
    }
    t.totalMs = Date.now() - start;
    return { info, fetch: { attempts: ctx.attempts, proxy: ctx.proxy, cached: false, timings: t } };
  });
  logTimings("info", id, result.fetch);
  return result;
}

export interface TranscriptResult {
  info: VideoInfo;
  choice: TrackChoice;
  segments: Segment[];
  fetch: FetchMeta;
}

/** Metadata + one transcript, fetched within a single proxy session: ANDROID player call, then timedtext. */
export async function getTranscript(id: string, opts: TrackOptions): Promise<TranscriptResult> {
  const start = Date.now();
  const cachedInfo = infoCache.get(id);
  if (cachedInfo) {
    const choice = selectTrack(cachedInfo, opts);
    const segs = transcriptCache.get(trackKey(id, choice));
    if (segs) {
      return {
        info: cachedInfo,
        choice,
        segments: segs,
        fetch: { attempts: 0, proxy: null, cached: true, timings: { ...newTimings(), totalMs: Date.now() - start } },
      };
    }
  }
  const result = await withYouTube(async (http, ctx) => {
    const t = newTimings();
    t.proxySetupMs = ctx.proxySetupMs;
    // Caption URLs are signed for the session's IP: reuse cached player data only from the same session.
    const reusable = cachedInfo && infoSession.get(id) === ctx.sessionId ? cachedInfo : null;
    let info = reusable;
    if (!info) {
      info = await loadInfo(http, id, t, false);
      infoSession.set(id, ctx.sessionId);
    }
    const choice = selectTrack(info, opts);
    const key = trackKey(id, choice);
    let segments = transcriptCache.get(key);
    if (!segments) {
      segments = await timed(t, "timedtextMs", () => fetchTimedText(http, id, choice));
      if (!segments.length) {
        throw new YouTubeError(ErrorCodes.EMPTY_TRANSCRIPT, `The ${choice.track.languageCode} transcript of ${id} is empty.`, {
          videoId: id,
        });
      }
      transcriptCache.set(key, segments);
    }
    t.totalMs = Date.now() - start;
    return { info, choice, segments, fetch: { attempts: ctx.attempts, proxy: ctx.proxy, cached: false, timings: t } };
  });
  logTimings("transcript", id, result.fetch);
  return result;
}

function trackKey(id: string, c: TrackChoice): string {
  return `${id}|${c.track.languageCode}|${c.track.autoGenerated ? "asr" : "manual"}|${c.translatedTo ?? ""}`;
}
