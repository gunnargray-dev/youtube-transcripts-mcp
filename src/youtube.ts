export interface TrackOptions {
  /** Preferred language codes, in priority order. */
  languages: string[];
  allowAutoGenerated: boolean;
  /** Use any available track when none of `languages` exists. */
  fallbackToAny: boolean;
  translateTo?: string;
}

export interface TrackChoice {
  track: CaptionTrack;
  matchedPreference: boolean;
  translatedTo: string | null;
}

const base = (code: string) => code.toLowerCase().split("-")[0]!;

/**
 * Pick a caption track like youtube-transcript-api's `find_transcript`: for each
 * preferred language in order, manual captions win over auto-generated ones;
 * an exact code match wins over a base-language match ("en" ↔ "en-GB").
 */
export function selectTrack(info: Pick<VideoInfo, "id" | "tracks" | "translationLanguages">, opts: TrackOptions): TrackChoice {
  if (!info.tracks.length) {
    throw new YouTubeError(ErrorCodes.TRANSCRIPTS_DISABLED, `Subtitles/transcripts are disabled for video ${info.id}.`, {
      videoId: info.id,
    });
  }
  const usable = info.tracks.filter((t) => opts.allowAutoGenerated || !t.autoGenerated);
  const prefs = opts.languages.map(normalizeLang);
  let picked: CaptionTrack | undefined;
  for (const p of prefs) {
    const pl = p.toLowerCase();
    const candidates = [
      (t: CaptionTrack) => !t.autoGenerated && t.languageCode.toLowerCase() === pl,
      (t: CaptionTrack) => !t.autoGenerated && base(t.languageCode) === base(p),
      (t: CaptionTrack) => t.autoGenerated && t.languageCode.toLowerCase() === pl,
      (t: CaptionTrack) => t.autoGenerated && base(t.languageCode) === base(p),
    ];
    for (const pred of candidates) {
      picked = usable.find(pred);
      if (picked) break;
    }
    if (picked) break;
  }
  const matchedPreference = !!picked;
  if (!picked && (opts.fallbackToAny || opts.translateTo)) {
    picked = usable.find((t) => !t.autoGenerated) ?? usable[0];
  }
  if (!picked) {
    throw new YouTubeError(
      ErrorCodes.NO_TRANSCRIPT_FOUND,
      `No transcript in ${prefs.join(", ") || "the requested languages"}${opts.allowAutoGenerated ? "" : " (manual captions only)"} for video ${info.id}. ` +
        `Available: ${info.tracks.map((t) => `${t.languageCode}${t.autoGenerated ? " (auto)" : ""}`).join(", ")}.`,
      { videoId: info.id, requested: prefs, available: info.tracks.map(({ baseUrl: _b, ...t }) => t) },
    );
  }

  let translatedTo: string | null = null;
  if (opts.translateTo) {
    const target = normalizeLang(opts.translateTo);
    if (target.toLowerCase() !== picked.languageCode.toLowerCase()) {
      const direct = info.tracks.find(
        (t) => t.languageCode.toLowerCase() === target.toLowerCase() && (opts.allowAutoGenerated || !t.autoGenerated),
      );
      if (direct) {
        return { track: direct, matchedPreference, translatedTo: null };
      }
      const supported =
        !info.translationLanguages.length ||
        info.translationLanguages.some((l) => l.languageCode.toLowerCase() === target.toLowerCase());
      if (!picked.translatable || !supported) {
        throw new YouTubeError(
          ErrorCodes.TRANSLATION_UNAVAILABLE,
          `The ${picked.languageCode} transcript of ${info.id} cannot be translated to ${target}.`,
          { videoId: info.id, source: picked.languageCode, target },
        );
      }
      translatedTo = target;
    }
  }
  return { track: picked, matchedPreference, translatedTo };
}

async function fetchTimedText(http: HttpClient, id: string, choice: TrackChoice): Promise<Segment[]> {
  const raw = choice.track.baseUrl;
  if (raw.includes("&exp=xpe")) {
    throw new YouTubeError(
      ErrorCodes.PO_TOKEN_REQUIRED,
      `YouTube requires a PO token to download captions for ${id}; this client cannot fetch them right now.`,
      { videoId: id },
    );
  }
  const url = new URL(raw);
  url.searchParams.delete("fmt"); // default format = srv1 XML, the same as youtube-transcript-api
  if (choice.translatedTo) url.searchParams.set("tlang", choice.translatedTo);
  const res = await http.request({ method: "GET", url: url.toString() });
  if (res.status === 403) {
    throw new YouTubeError(ErrorCodes.REQUEST_BLOCKED, "YouTube refused the caption download (HTTP 403).", { httpStatus: 403 });
  }
  if (res.status >= 400) {
    throw new YouTubeError(ErrorCodes.UPSTREAM_ERROR, `YouTube timedtext responded ${res.status}`, { httpStatus: res.status });
  }
  if (!res.text.trim()) {
    throw new YouTubeError(
      ErrorCodes.EMPTY_TRANSCRIPT,
      `YouTube returned an empty caption file for ${id} (${choice.track.languageCode}).`,
      { videoId: id },
    );
  }
  return parseTimedText(res.text);
}

