interface PlayerResponse {
  playabilityStatus?: {
    status?: string;
    reason?: string;
    messages?: string[];
    errorScreen?: { playerErrorMessageRenderer?: { subreason?: unknown; reason?: unknown } };
  };
  videoDetails?: {
    videoId?: string;
    title?: string;
    author?: string;
    channelId?: string;
    lengthSeconds?: string;
    viewCount?: string;
    shortDescription?: string;
    keywords?: string[];
    isLiveContent?: boolean;
    isLive?: boolean;
  };
  microformat?: { playerMicroformatRenderer?: { publishDate?: string; uploadDate?: string; category?: string } };
  captions?: {
    playerCaptionsTracklistRenderer?: {
      captionTracks?: {
        baseUrl?: string;
        name?: unknown;
        languageCode?: string;
        kind?: string;
        isTranslatable?: boolean;
        vssId?: string;
      }[];
      translationLanguages?: { languageCode?: string; languageName?: unknown }[];
    };
  };
}

/** Map InnerTube playabilityStatus to a typed error (mirrors youtube-transcript-api). */
export function assertPlayable(player: PlayerResponse, id: string): void {
  const ps = player.playabilityStatus;
  const status = ps?.status;
  if (!status || status === "OK") return;
  const reason = (ps?.reason ?? ps?.messages?.join(" ") ?? textOf(ps?.errorScreen?.playerErrorMessageRenderer?.reason)).trim();
  const subreason = textOf(ps?.errorScreen?.playerErrorMessageRenderer?.subreason).trim();
  const details = { videoId: id, playabilityStatus: status, reason: reason || null, ...(subreason ? { subreason } : {}) };
  const text = `${reason} ${subreason}`;

  if (/not a bot/i.test(text)) {
    throw new YouTubeError(
      ErrorCodes.REQUEST_BLOCKED,
      `YouTube asked to "confirm you're not a bot" for ${id}: this IP is blocked.`,
      { ...details, botCheck: true },
    );
  }
  if (/private/i.test(text)) {
    throw new YouTubeError(ErrorCodes.VIDEO_PRIVATE, `Video ${id} is private.`, details);
  }
  if (status === "LOGIN_REQUIRED" && /inappropriate|confirm your age|age-restricted|age restricted/i.test(text)) {
    throw new YouTubeError(
      ErrorCodes.AGE_RESTRICTED,
      `Video ${id} is age-restricted; YouTube requires a signed-in account to access it.`,
      details,
    );
  }
  if (status === "ERROR") {
    throw new YouTubeError(
      ErrorCodes.VIDEO_UNAVAILABLE,
      `Video ${id} is unavailable${reason ? ` (${reason})` : ""}. It may have been removed or the id is wrong.`,
      details,
    );
  }
  throw new YouTubeError(
    ErrorCodes.VIDEO_UNPLAYABLE,
    `Video ${id} is not playable${reason ? `: ${reason}` : ""}${subreason ? ` (${subreason})` : ""}`,
    details,
  );
}

async function fetchPlayer(http: HttpClient, id: string, apiKey: string | null = null): Promise<PlayerResponse> {
  const url = `${PLAYER_URL}?${apiKey ? `key=${apiKey}&` : ""}prettyPrint=false`;
  const res = await http.request({
    method: "POST",
    url,
    body: JSON.stringify({ context: INNERTUBE_ANDROID_CONTEXT, videoId: id }),
  });
  if (res.status >= 400) {
    throw new YouTubeError(ErrorCodes.UPSTREAM_ERROR, `YouTube player API responded ${res.status}`, { httpStatus: res.status });
  }
  try {
    return JSON.parse(res.text) as PlayerResponse;
  } catch {
    throw new YouTubeError(ErrorCodes.UPSTREAM_ERROR, "YouTube player API returned a non-JSON response");
  }
}

export function parseCaptionTracks(player: PlayerResponse): Pick<VideoInfo, "tracks" | "translationLanguages"> {
  const r = player.captions?.playerCaptionsTracklistRenderer;
  const tracks: CaptionTrack[] = (r?.captionTracks ?? [])
    .filter((t) => t.baseUrl && t.languageCode)
    .map((t) => ({
      languageCode: t.languageCode!,
      languageName: textOf(t.name).replace(/\s*\(auto-generated\)\s*$/i, "").trim() || t.languageCode!,
      autoGenerated: t.kind === "asr" || (t.vssId ?? "").startsWith("a."),
      translatable: !!t.isTranslatable,
      baseUrl: decodeEntities(t.baseUrl!),
    }));
  const translationLanguages = (r?.translationLanguages ?? [])
    .filter((l) => l.languageCode)
    .map((l) => ({ languageCode: l.languageCode!, languageName: textOf(l.languageName) || l.languageCode! }));
  return { tracks, translationLanguages };
}

export function buildVideoInfo(id: string, player: PlayerResponse, page: WatchPage | null): VideoInfo {
  const d = player.videoDetails ?? {};
  const num = (s?: string) => (s && /^\d+$/.test(s) ? Number(s) : null);
  return {
    id,
    url: videoUrl(id),
    title: d.title ?? "",
    channel: d.author ?? null,
    channelId: d.channelId ?? null,
    durationSeconds: num(d.lengthSeconds),
    viewCount: num(d.viewCount),
    publishDate: page?.publishDate ?? player.microformat?.playerMicroformatRenderer?.publishDate ?? null,
    category: page?.category ?? player.microformat?.playerMicroformatRenderer?.category ?? null,
    isLive: !!d.isLive,
    keywords: d.keywords ?? [],
    description: d.shortDescription ?? "",
    ...parseCaptionTracks(player),
    markerChapters: page?.markerChapters ?? null,
    watchLoaded: !!page,
  };
}

/** InnerTube ANDROID player call; falls back to the watch page (for the API key) only if the keyless call is rejected. */
async function loadPlayer(
  http: HttpClient,
  id: string,
  t: FetchTimings,
  watch: Promise<WatchPage> | null,
): Promise<{ player: PlayerResponse; page: WatchPage | null }> {
  try {
    const player = await timed(t, "playerMs", () => fetchPlayer(http, id));
    return { player, page: null };
  } catch (err) {
    const status = err instanceof YouTubeError ? (err.details as { httpStatus?: number } | undefined)?.httpStatus : undefined;
    if (!status || status >= 500 || status === 429) throw err;
    const page = await (watch ?? timed(t, "watchPageMs", () => fetchWatchPage(http, id)));
    const player = await timed(t, "playerMs", () => fetchPlayer(http, id, page.apiKey));
    return { player, page };
  }
}

/** Metadata + caption tracks. The watch page is only requested (in parallel with the player call) when `withWatch`. */
async function loadInfo(http: HttpClient, id: string, t: FetchTimings, withWatch: boolean): Promise<VideoInfo> {
  const watch = withWatch ? timed(t, "watchPageMs", () => fetchWatchPage(http, id)) : null;
  const [playerRes, watchRes] = await Promise.allSettled([loadPlayer(http, id, t, watch), watch ?? Promise.resolve(null)]);
  // A block (captcha) on the watch page is the more useful diagnosis than whatever the player call returned.
  if (watchRes.status === "rejected" && watchRes.reason instanceof YouTubeError && watchRes.reason.code === ErrorCodes.REQUEST_BLOCKED) {
    throw watchRes.reason;
  }
  if (playerRes.status === "rejected") throw playerRes.reason;
  if (watchRes.status === "rejected") throw watchRes.reason;
  const { player, page: fallbackPage } = playerRes.value;
  assertPlayable(player, id);
  const info = buildVideoInfo(id, player, watchRes.value ?? fallbackPage);
  infoCache.set(id, info);
  return info;
}

