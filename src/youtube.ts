interface WatchPage {
  apiKey: string | null;
  publishDate: string | null;
  category: string | null;
  markerChapters: VideoInfo["markerChapters"];
}

/** Extract the JSON object literal that follows `marker` (brace matching, string-aware). */
export function extractJsonAfter(html: string, marker: string): unknown {
  const at = html.indexOf(marker);
  if (at < 0) return null;
  const start = html.indexOf("{", at + marker.length);
  if (start < 0) return null;
  let depth = 0;
  let inStr = false;
  for (let i = start; i < html.length; i++) {
    const c = html[i];
    if (inStr) {
      if (c === "\\") i++;
      else if (c === '"') inStr = false;
    } else if (c === '"') inStr = true;
    else if (c === "{") depth++;
    else if (c === "}" && --depth === 0) {
      try {
        return JSON.parse(html.slice(start, i + 1));
      } catch {
        return null;
      }
    }
  }
  return null;
}

/** Depth-first search for every value stored under `key`. */
function findAll(node: unknown, key: string, out: unknown[] = [], depth = 0): unknown[] {
  if (!node || typeof node !== "object" || depth > 60) return out;
  if (Array.isArray(node)) {
    for (const v of node) findAll(v, key, out, depth + 1);
    return out;
  }
  for (const [k, v] of Object.entries(node)) {
    if (k === key) out.push(v);
    findAll(v, key, out, depth + 1);
  }
  return out;
}

export function textOf(node: unknown): string {
  if (!node || typeof node !== "object") return typeof node === "string" ? node : "";
  const n = node as { simpleText?: string; runs?: { text?: string }[]; content?: string };
  if (typeof n.simpleText === "string") return n.simpleText;
  if (Array.isArray(n.runs)) return n.runs.map((r) => r.text ?? "").join("");
  if (typeof n.content === "string") return n.content;
  return "";
}

export function parseMarkerChapters(initialData: unknown): VideoInfo["markerChapters"] {
  const maps = findAll(initialData, "markersMap").flat() as { key?: string; value?: { chapters?: unknown[] } }[];
  let auto: MarkerChapter[] | null = null;
  for (const m of maps) {
    const chapters = (m?.value?.chapters ?? [])
      .map((c) => (c as { chapterRenderer?: { title?: unknown; timeRangeStartMillis?: number } }).chapterRenderer)
      .filter((c): c is { title?: unknown; timeRangeStartMillis?: number } => !!c)
      .map((c) => ({ title: textOf(c.title).trim(), start: (c.timeRangeStartMillis ?? 0) / 1000 }))
      .filter((c) => c.title);
    if (chapters.length < 2) continue;
    if (m.key === "DESCRIPTION_CHAPTERS") return { kind: "description", chapters };
    if (m.key === "AUTO_CHAPTERS") auto = chapters;
  }
  return auto ? { kind: "auto", chapters: auto } : null;
}

async function fetchWatchPage(http: HttpClient, id: string): Promise<WatchPage> {
  let res = await http.request({ method: "GET", url: `${WATCH_URL}${id}&hl=en` });
  if (res.text.includes('action="https://consent.youtube.com/s"')) {
    // EU consent interstitial: accept via cookie and retry once (same as youtube-transcript-api).
    const v = res.text.match(/name="v" value="(.*?)"/)?.[1];
    if (!v) throw new YouTubeError(ErrorCodes.UPSTREAM_ERROR, "Could not accept YouTube's cookie consent page");
    res = await http.request({ method: "GET", url: `${WATCH_URL}${id}&hl=en`, headers: { Cookie: `CONSENT=YES+${v}` } });
    if (res.text.includes('action="https://consent.youtube.com/s"')) {
      throw new YouTubeError(ErrorCodes.UPSTREAM_ERROR, "YouTube cookie consent could not be accepted");
    }
  }
  if (res.text.includes('class="g-recaptcha"')) {
    throw new YouTubeError(
      ErrorCodes.REQUEST_BLOCKED,
      "YouTube answered with a reCAPTCHA challenge: this IP is blocked.",
      { captcha: true },
    );
  }
  if (res.status >= 400) {
    throw new YouTubeError(ErrorCodes.UPSTREAM_ERROR, `YouTube watch page responded ${res.status}`, { httpStatus: res.status });
  }
  const html = res.text;
  return {
    apiKey: html.match(/"INNERTUBE_API_KEY":\s*"([a-zA-Z0-9_-]+)"/)?.[1] ?? null,
    publishDate: html.match(/"publishDate":\s*"([^"]+)"/)?.[1] ?? null,
    category: html.match(/"category":\s*"([^"]+)"/)?.[1] ?? null,
    markerChapters: parseMarkerChapters(extractJsonAfter(html, "ytInitialData")),
  };
}

