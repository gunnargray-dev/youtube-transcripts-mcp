import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import type { CallToolResult } from "@modelcontextprotocol/sdk/types.js";
import { z } from "zod";
import { BillingEvents, chargeEvent } from "./billing.js";
import { type RawChapter, deriveChapters, finalizeChapters, parseDescriptionChapters } from "./chapters.js";
import { DURATIONS, FEATURES, SORTS, UPLOAD_DATES, searchVideos } from "./search.js";
import { summarize } from "./summary.js";
import { buildSentences } from "./text.js";
import { type Segment, segmentsEnd, toPlainText, toSrt } from "./transcript.js";
import { ErrorCodes, YouTubeError, errorMessage, formatTimestamp, parseVideoId, round } from "./util.js";
import { type FetchMeta, type TranscriptResult, type VideoInfo, getTranscript, getVideoInfo } from "./youtube.js";

export const SERVER_NAME = "youtube-transcripts-mcp";
export const SERVER_VERSION = "1.0.0";

// ---------------------------------------------------------------------------
// Shared input schemas
// ---------------------------------------------------------------------------

const videoSchema = z
  .string()
  .trim()
  .min(1)
  .max(500)
  .describe("YouTube video id (e.g. dQw4w9WgXcQ) or URL (watch?v=, youtu.be/, /shorts/, /embed/, /live/)");

const languagesSchema = z
  .array(z.string().trim().regex(/^[A-Za-z]{2,3}([-_][A-Za-z0-9]{2,8})*$/, "must be a language code like 'en' or 'pt-BR'"))
  .min(1)
  .max(10)
  .default(["en"])
  .describe('Preferred caption languages in priority order, e.g. ["en", "de"]. Manual captions beat auto-generated ones. Default ["en"].');

const READ_ONLY = { readOnlyHint: true, destructiveHint: false, idempotentHint: true, openWorldHint: true } as const;

// ---------------------------------------------------------------------------
// Result helpers
// ---------------------------------------------------------------------------

function ok(data: Record<string, unknown>): CallToolResult {
  return {
    content: [{ type: "text", text: JSON.stringify(data, null, 2) }],
    structuredContent: data,
  };
}

export function toErrorPayload(err: unknown): { code: string; message: string; retryable: boolean; details?: Record<string, unknown> } {
  if (err instanceof YouTubeError) {
    return {
      code: err.code,
      message: err.message,
      retryable: err.retryable,
      ...(Object.keys(err.details).length ? { details: err.details } : {}),
    };
  }
  return { code: ErrorCodes.INTERNAL_ERROR, message: errorMessage(err), retryable: false };
}

function fail(err: unknown): CallToolResult {
  const error = toErrorPayload(err);
  if (error.code === ErrorCodes.INTERNAL_ERROR) console.error("[tool] unexpected error:", err);
  return {
    isError: true,
    content: [{ type: "text", text: `Error (${error.code}): ${error.message}` }],
    structuredContent: { error },
  };
}

/** Wrap a handler so every failure becomes a well-formed MCP tool error. */
function safe<A>(fn: (args: A) => Promise<CallToolResult>): (args: A) => Promise<CallToolResult> {
  return async (args: A) => {
    try {
      return await fn(args);
    } catch (err) {
      return fail(err);
    }
  };
}

function videoBrief(info: VideoInfo) {
  return {
    id: info.id,
    url: info.url,
    title: info.title,
    channel: info.channel,
    channelId: info.channelId,
    durationSeconds: info.durationSeconds,
    duration: info.durationSeconds !== null ? formatTimestamp(info.durationSeconds) : null,
    viewCount: info.viewCount,
    publishDate: info.publishDate,
    category: info.category,
    isLive: info.isLive,
  };
}

function availableLanguages(info: VideoInfo) {
  return info.tracks.map((t) => ({
    languageCode: t.languageCode,
    languageName: t.languageName,
    autoGenerated: t.autoGenerated,
    translatable: t.translatable,
  }));
}

function transcriptMeta(r: TranscriptResult) {
  return {
    language: r.choice.translatedTo ?? r.choice.track.languageCode,
    languageName: r.choice.translatedTo
      ? (r.info.translationLanguages.find((l) => l.languageCode === r.choice.translatedTo)?.languageName ?? r.choice.translatedTo)
      : r.choice.track.languageName,
    autoGenerated: r.choice.track.autoGenerated,
    translatedFrom: r.choice.translatedTo ? r.choice.track.languageCode : null,
    matchedPreference: r.choice.matchedPreference,
  };
}

function fetchInfo(f: FetchMeta) {
  return { cached: f.cached, attempts: f.attempts, ...(f.proxy ? { proxy: f.proxy } : {}), timings: f.timings };
}

/** Creator chapters from the description, else chapter markers on the watch page. */
function creatorChapters(info: VideoInfo): { chapters: RawChapter[]; source: "description" | "youtube" } | null {
  const fromDesc = parseDescriptionChapters(info.description, info.durationSeconds);
  if (fromDesc.length >= 2) return { chapters: fromDesc, source: "description" };
  if (info.markerChapters?.chapters.length) return { chapters: info.markerChapters.chapters, source: "youtube" };
  return null;
}

const wordCount = (segs: Segment[]) => segs.reduce((n, s) => n + s.text.split(/\s+/).filter(Boolean).length, 0);

// ---------------------------------------------------------------------------
// Server factory
// ---------------------------------------------------------------------------

export function createServer(): McpServer {
  const server = new McpServer(
    { name: SERVER_NAME, version: SERVER_VERSION },
    {
      instructions:
        "YouTube transcripts for AI agents. Use search_videos to find videos, get_transcript for the full transcript " +
        "(text, timestamped segments or SRT) plus video metadata and available caption languages, get_video_chapters " +
        "for creator chapters (or topic segments derived from the transcript), and summarize_transcript for an " +
        "extractive summary with key points, keywords, per-chapter bullets and timestamped quotes. Errors carry a " +
        "stable code (e.g. TRANSCRIPTS_DISABLED, NO_TRANSCRIPT_FOUND, AGE_RESTRICTED, REQUEST_BLOCKED).",
    },
  );

  // (1) get_transcript -------------------------------------------------------
  server.registerTool(
    "get_transcript",
    {
      title: "Get YouTube transcript",
      description:
        "Fetch the transcript (captions) of a YouTube video plus metadata: title, channel, duration, views, publish " +
        "date, available caption languages and whether the returned transcript is auto-generated. Formats: 'text' " +
        "(plain text; with include_timestamps, ~30 s paragraphs prefixed [m:ss]), 'segments' (array of {start, " +
        "duration, text}) or 'srt'. Can machine-translate captions via YouTube (translate_to).",
      inputSchema: {
        video: videoSchema,
        languages: languagesSchema,
        format: z.enum(["text", "segments", "srt"]).default("text").describe("Output format. Default 'text'."),
        include_timestamps: z
          .boolean()
          .default(false)
          .describe("text: prefix paragraphs with [m:ss]; segments: add a 'time' string. SRT always has timing."),
        translate_to: z
          .string()
          .trim()
          .regex(/^[A-Za-z]{2,3}([-_][A-Za-z0-9]{2,8})*$/)
          .optional()
          .describe("Optional target language code; YouTube translates the best available track."),
        allow_auto_generated: z.boolean().default(true).describe("Allow auto-generated (ASR) captions. Default true."),
        fallback_to_any_language: z
          .boolean()
          .default(true)
          .describe("If none of `languages` exists, return the best available track instead of failing. Default true."),
        max_chars: z
          .number()
          .int()
          .min(500)
          .max(2_000_000)
          .optional()
          .describe("Truncate the transcript content to about this many characters (sets truncated=true)."),
      },
      annotations: { title: "Get YouTube transcript", ...READ_ONLY },
    },
    safe(async ({ video, languages, format, include_timestamps, translate_to, allow_auto_generated, fallback_to_any_language, max_chars }) => {
      const id = parseVideoId(video);
      const r = await getTranscript(id, {
        languages,
        allowAutoGenerated: allow_auto_generated,
        fallbackToAny: fallback_to_any_language,
        translateTo: translate_to,
      });

      let truncated = false;
      let body: Record<string, unknown>;
      if (format === "segments") {
        let segs = r.segments;
        if (max_chars) {
          let used = 0;
          const cut = segs.findIndex((s) => (used += s.text.length + 1) > max_chars);
          if (cut >= 0) {
            segs = segs.slice(0, cut);
            truncated = true;
          }
        }
        body = {
          segments: segs.map((s) => ({
            start: s.start,
            duration: s.duration,
            ...(include_timestamps ? { time: formatTimestamp(s.start) } : {}),
            text: s.text,
          })),
        };
      } else {
        let content = format === "srt" ? toSrt(r.segments) : toPlainText(r.segments, include_timestamps);
        if (max_chars && content.length > max_chars) {
          const cut = content.lastIndexOf(format === "srt" ? "\n\n" : " ", max_chars);
          content = content.slice(0, cut > max_chars * 0.8 ? cut : max_chars);
          truncated = true;
        }
        body = { content };
      }

      const meta = transcriptMeta(r);
      const notes: string[] = [];
      if (!meta.matchedPreference && !meta.translatedFrom) {
        notes.push(`No transcript in ${languages.join(", ")}; returned ${meta.language}${meta.autoGenerated ? " (auto-generated)" : ""} instead.`);
      }
      if (truncated) notes.push(`Content truncated to max_chars=${max_chars}.`);

      await chargeEvent(BillingEvents.TRANSCRIPT, 1);
      return ok({
        video: videoBrief(r.info),
        transcript: {
          ...meta,
          format,
          segmentCount: r.segments.length,
          wordCount: wordCount(r.segments),
          durationSeconds: round(segmentsEnd(r.segments), 2),
          truncated,
          ...body,
        },
        availableLanguages: availableLanguages(r.info),
        translationLanguagesCount: r.info.translationLanguages.length,
        ...(notes.length ? { notes } : {}),
        fetch: fetchInfo(r.fetch),
      });
    }),
  );

  // (2) search_videos ----------------------------------------------------------
  server.registerTool(
    "search_videos",
    {
      title: "Search YouTube videos",
      description:
        "Search YouTube videos by keyword (YouTube's InnerTube search API, the same one the website uses). Returns " +
        "video id, title, channel, duration, views, relative publish time, description snippet, thumbnail and " +
        "badges. Optional filters: upload_date, duration (short <4 min, medium 4-20 min, long >20 min), sort_by, " +
        "and features (e.g. 'subtitles' = only videos with captions).",
      inputSchema: {
        query: z.string().trim().min(1).max(300).describe("Search keywords"),
        limit: z.number().int().min(1).max(50).default(10).describe("Max results (1-50). Default 10."),
        upload_date: z.enum(UPLOAD_DATES).optional().describe("Only videos uploaded within the last hour/today/week/month/year"),
        duration: z.enum(DURATIONS).optional().describe("short (< 4 min), medium (4-20 min) or long (> 20 min)"),
        sort_by: z.enum(SORTS).default("relevance").describe("Result order. Default relevance."),
        features: z
          .array(z.enum(FEATURES))
          .max(5)
          .optional()
          .describe("Feature filters, e.g. ['subtitles'] for videos with captions, ['live'], ['hd'], ['creative_commons']"),
        hl: z.string().trim().regex(/^[A-Za-z]{2}(-[A-Za-z]{2})?$/).default("en").describe("Interface language for result text. Default en."),
        gl: z.string().trim().regex(/^[A-Za-z]{2}$/).default("US").describe("Region (2-letter country code). Default US."),
      },
      annotations: { title: "Search YouTube videos", ...READ_ONLY },
    },
    safe(async ({ query, limit, upload_date, duration, sort_by, features, hl, gl }) => {
      const filters = { uploadDate: upload_date, duration, sortBy: sort_by, features };
      const res = await searchVideos(query, limit, filters, { hl, gl });
      await chargeEvent(BillingEvents.SEARCH, 1);
      return ok({
        query,
        filters: {
          ...(upload_date ? { upload_date } : {}),
          ...(duration ? { duration } : {}),
          sort_by,
          ...(features?.length ? { features } : {}),
          hl,
          gl: gl.toUpperCase(),
        },
        count: res.videos.length,
        ...(res.estimatedResults !== null ? { estimatedResults: res.estimatedResults } : {}),
        ...(res.videos.length === 0 ? { note: "No videos matched. Try fewer filters or different keywords." } : {}),
        videos: res.videos,
      });
    }),
  );

  // (3) get_video_chapters -------------------------------------------------------
  server.registerTool(
    "get_video_chapters",
    {
      title: "Get video chapters",
      description:
        "Chapters of a YouTube video with start/end times and deep links. Uses the creator's chapters from the " +
        "description (or YouTube's chapter markers) when present; otherwise derives topic segments from the " +
        "transcript (time windows + keyword-shift detection) and titles them with their distinctive keywords and a " +
        "representative sentence.",
      inputSchema: {
        video: videoSchema,
        source: z
          .enum(["auto", "description", "transcript"])
          .default("auto")
          .describe("auto (default): creator chapters, else derived; description: creator chapters only; transcript: always derive"),
        languages: languagesSchema,
        target_chapters: z
          .number()
          .int()
          .min(2)
          .max(30)
          .optional()
          .describe("Derived chapters only: desired number of chapters (default scales with video length)"),
      },
      annotations: { title: "Get video chapters", ...READ_ONLY },
    },
    safe(async ({ video, source, languages, target_chapters }) => {
      const id = parseVideoId(video);
      let result: Record<string, unknown>;

      const { info, fetch } = await getVideoInfo(id);
      const creator = source === "transcript" ? null : creatorChapters(info);
      if (creator) {
        const chapters = finalizeChapters(id, creator.chapters, info.durationSeconds);
        result = { video: videoBrief(info), source: creator.source, chapterCount: chapters.length, chapters, fetch: fetchInfo(fetch) };
      } else if (source === "description") {
        throw new YouTubeError(ErrorCodes.NO_CHAPTERS, `Video ${id} has no chapters in its description.`, { videoId: id });
      } else {
        const r = await getTranscript(id, { languages, allowAutoGenerated: true, fallbackToAny: true });
        const sentences = buildSentences(r.segments);
        const total = Math.max(r.info.durationSeconds ?? 0, segmentsEnd(r.segments));
        const chapters = deriveChapters(id, sentences, total, { targetChapters: target_chapters });
        result = {
          video: videoBrief(r.info),
          source: "transcript",
          chapterCount: chapters.length,
          chapters,
          transcript: transcriptMeta(r),
          note: "No creator chapters found; chapters were derived from topic shifts in the transcript.",
          fetch: fetchInfo(r.fetch),
        };
      }
      await chargeEvent(BillingEvents.CHAPTERS, 1);
      return ok(result);
    }),
  );

  // (4) summarize_transcript -------------------------------------------------------
  server.registerTool(
    "summarize_transcript",
    {
      title: "Summarize transcript (extractive)",
      description:
        "Structured extractive summary of a YouTube video without an LLM: TL;DR, key points (TextRank over TF-IDF " +
        "sentence similarity, de-duplicated), keywords/keyphrases, bullets per chapter (creator chapters or derived " +
        "topic segments) and notable quotes. Every point carries a timestamp and a deep link to that moment.",
      inputSchema: {
        video: videoSchema,
        max_points: z.number().int().min(1).max(30).default(8).describe("Number of key points (1-30). Default 8."),
        languages: languagesSchema,
        bullets_per_chapter: z.number().int().min(1).max(5).default(2).describe("Bullets per chapter (1-5). Default 2."),
        max_quotes: z.number().int().min(0).max(10).default(3).describe("Notable quotes to include (0-10). Default 3."),
        keyword_limit: z.number().int().min(1).max(40).default(12).describe("Number of keywords (1-40). Default 12."),
      },
      annotations: { title: "Summarize transcript (extractive)", ...READ_ONLY },
    },
    safe(async ({ video, max_points, languages, bullets_per_chapter, max_quotes, keyword_limit }) => {
      const id = parseVideoId(video);
      const r = await getTranscript(id, { languages, allowAutoGenerated: true, fallbackToAny: true });
      const creator = creatorChapters(r.info);
      const s = summarize(id, r.segments, {
        maxPoints: max_points,
        bulletsPerChapter: bullets_per_chapter,
        maxQuotes: max_quotes,
        keywordLimit: keyword_limit,
        chapters: creator?.chapters ?? null,
        chapterSource: creator?.source,
        durationSeconds: r.info.durationSeconds,
      });
      await chargeEvent(BillingEvents.SUMMARY, 1);
      return ok({
        video: videoBrief(r.info),
        transcript: transcriptMeta(r),
        method: "extractive (TextRank + TF-IDF + MMR); no LLM",
        ...s,
        fetch: fetchInfo(r.fetch),
      });
    }),
  );

  return server;
}
